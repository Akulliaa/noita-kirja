// Builds the ready-to-install tracker mod (zip) with the player's key inside.
import { zipSync, strToU8 } from 'fflate';
import modXml from '../../mod/noita_kirja_tracker/mod.xml?raw';
import initLua from '../../mod/noita_kirja_tracker/init.lua?raw';
import { SUPABASE_KEY, SUPABASE_URL } from './config';

export function buildModZip(key: string, radius: number): Uint8Array {
  const config = `-- Generated by the Noita Kirja website (Tracker page). Do not share: the key identifies you.
return {
  url = "${SUPABASE_URL}/rest/v1/rpc/track",
  apikey = "${SUPABASE_KEY}",
  key = "${key}",
  radius = ${Math.round(radius)},
}
`;
  const readme = `Noita Kirja Tracker
===================
1. Put this "noita_kirja_tracker" folder inside Noita's "mods" folder.
2. In Noita: Mods -> enable "Noita Kirja Tracker" (and unsafe mods).
3. Start a run: "Noita Kirja: tracker active", then "Noita Kirja: connected" appear.
If nothing shows up on the map, type %TEMP% in the Explorer address bar and
open noita_kirja_log.txt and noita_kirja_response.txt.
`;
  return zipSync({
    noita_kirja_tracker: {
      'mod.xml': strToU8(modXml),
      'init.lua': strToU8(initLua),
      'config.lua': strToU8(config),
      'README.txt': strToU8(readme),
    },
  });
}

export function download(data: Uint8Array, name: string) {
  const url = URL.createObjectURL(new Blob([data as BlobPart], { type: 'application/zip' }));
  const a = document.createElement('a');
  a.href = url; a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}
